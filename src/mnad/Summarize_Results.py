import argparse
import csv
import os

import numpy as np
from sklearn.metrics import roc_auc_score


parser = argparse.ArgumentParser(description='Summarize MNAD experiment AUC results')
parser.add_argument('--result_dir', required=True, help='directory containing score npz files')
parser.add_argument('--output', default=None, help='output CSV path')
args = parser.parse_args()

rows = []


def standalone_auc(score_name):
    """Return the branch AUC on its native paper-protocol frame set."""
    score_path = os.path.join(args.result_dir, score_name)
    if not os.path.isfile(score_path):
        return None
    score_data = np.load(score_path)
    return roc_auc_score(score_data['labels'], score_data['scores']) * 100.0


def add_group(prefix, r_name, p_name, fused_name, smooth_name):
    """Report paper-comparable branches plus explicitly aligned fusion diagnostics."""
    fused_path = os.path.join(args.result_dir, fused_name)
    if not os.path.isfile(fused_path):
        return

    fused = np.load(fused_path)
    labels = fused['labels']
    required = ('aligned_recons_scores', 'pred_scores')
    if not all(key in fused.files for key in required):
        raise KeyError(
            f'{fused_path} was generated by an older Fuse_Scores.py. '
            'Re-run score fusion before summarizing results.')

    r_native_auc = standalone_auc(r_name)
    p_native_auc = standalone_auc(p_name)
    if r_native_auc is not None:
        rows.append((f'{prefix} MNAD-R (all frames; paper protocol)',
                     r_native_auc, r_name))
    rows.append((f'{prefix} MNAD-R (fusion-aligned diagnostic)',
                 roc_auc_score(labels, fused['aligned_recons_scores']) * 100.0,
                 fused_name))
    if p_native_auc is not None:
        rows.append((f'{prefix} MNAD-P (paper protocol)', p_native_auc, p_name))
    else:
        rows.append((f'{prefix} MNAD-P (paper protocol)',
                     roc_auc_score(labels, fused['pred_scores']) * 100.0,
                     fused_name))
    rows.append((f'{prefix} R+P fusion',
                 roc_auc_score(labels, fused['scores']) * 100.0,
                 fused_name))

    smooth_path = os.path.join(args.result_dir, smooth_name)
    if os.path.isfile(smooth_path):
        smooth = np.load(smooth_path)
        rows.append((f'{prefix} R+P fusion + Gaussian',
                     roc_auc_score(smooth['labels'], smooth['scores']) * 100.0,
                     smooth_name))


add_group('Baseline', 'baseline_r.npz', 'baseline_p.npz',
          'baseline_fused.npz', 'baseline_fused_smooth.npz')
add_group('K-MNAD', 'kmeans_r.npz', 'kmeans_p.npz',
          'kmeans_fused.npz', 'kmeans_fused_smooth.npz')

if not rows:
    raise FileNotFoundError(f'No score files were found in {args.result_dir}')

if args.output is None:
    args.output = os.path.join(args.result_dir, 'auc_results.csv')
os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)

with open(args.output, 'w', newline='', encoding='utf-8') as csv_file:
    writer = csv.writer(csv_file)
    writer.writerow(['method', 'frame_auc_percent', 'score_file'])
    for method, auc, filename in rows:
        writer.writerow([method, f'{auc:.4f}', filename])

print('AUC summary')
for method, auc, _ in rows:
    print(f'{method:<38} {auc:.2f}%')
print('Summary saved to:', args.output)
